function renderPixelMap(textures: Phaser.Textures.TextureManager, key: string, map: PixelMap, palette: Palette, scale: number): void {
  const srcW = map[0].length;
  const srcH = map.length;
  const w = srcW * scale;
  const h = srcH * scale;
  const canvas = textures.createCanvas(key, w, h);
  if (!canvas) return;
  const ctx = canvas.context;
  for (let y = 0; y < srcH; y++) {
    for (let x = 0; x < srcW; x++) {
      const colorKey = map[y][x];
      if (colorKey === 0) continue;
      const color = palette[colorKey];
      if (color === undefined) continue;
      const r = (color >>> 16) & 0xff;
      const g = (color >>> 8) & 0xff;
      const b = color & 0xff;
      ctx.fillStyle = `rgb(${r},${g},${b})`;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  }
  canvas.refresh();
}

export function generateAllTextures(scene: Phaser.Scene): void {
  const textures = scene.textures;
  const s = 2;
  renderPixelMap(textures, 'player', PLAYER_MAP, P, s);
  renderPixelMap(textures, 'enemy', ENEMY_MAP, P, s);
  renderPixelMap(textures, 'wall', WALL_MAP, P, s);
  renderPixelMap(textures, 'ground', GROUND_MAP, P, s);
  renderPixelMap(textures, 'chest', CHEST_MAP, P, s);
  renderPixelMap(textures, 'exit', EXIT_MAP, P, s);
  renderPixelMap(textures, 'weapon_sword', SWORD_MAP, P, s);
  renderPixelMap(textures, 'weapon_staff', STAFF_MAP, P, s);
  renderPixelMap(textures, 'weapon_dagger', DAGGER_MAP, P, s);
}

export function generateLightTexture(scene: Phaser.Scene, key: string, radius: number): void {
  const size = radius * 2;
  const canvas = document.createElement('canvas');
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext('2d')!;
  const cx = radius, cy = radius;
  const g = ctx.createRadialGradient(cx, cy, 0, cx, cy, radius);
  g.addColorStop(0, 'rgba(255,255,255,1)');
  g.addColorStop(0.5, 'rgba(255,255,255,1)');
  g.addColorStop(0.75, 'rgba(255,255,255,0.3)');
  g.addColorStop(1, 'rgba(255,255,255,0)');
  ctx.fillStyle = g;
  ctx.fillRect(0, 0, size, size);
  scene.textures.addCanvas(key, canvas);
}
